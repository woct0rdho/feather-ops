#!/usr/bin/env python3
"""Compile `feather_ops/tiles.py` into the C++ instantiation lists.

    python tools/gen_tiles.py            # rewrite csrc/feather_tiles.h
    python tools/gen_tiles.py --check    # fail if the committed header is stale

`feather_ops/tiles.py` is the single source of truth for which tiles exist: the heuristics choose from
those lists and the kernels instantiate exactly them, so a tile the heuristic can return is always a
compiled kernel. `setup.py` runs this before the extension builds, and `tests/test_tiles.py` runs it with
`--check` so a hand-edited header does not survive.

`feather_ops/tiles.py` deliberately does not import torch, so it is loaded here by path instead of by
`import feather_ops` (which would need the compiled extension).
"""

import argparse
import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
TILES = ROOT / "feather_ops" / "tiles.py"
HEADER = ROOT / "csrc" / "feather_tiles.h"

BANNER = """// Generated by tools/gen_tiles.py from feather_ops/tiles.py. Do not edit.
"""


def load_tiles():
    spec = importlib.util.spec_from_file_location("_feather_tiles", TILES)
    assert spec is not None and spec.loader is not None, f"cannot load {TILES}"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render() -> str:
    tiles = load_tiles()
    lines = [BANNER]

    def macro(name: str, rows: list[tuple[int, ...]], comment: str) -> None:
        lines.append(f"// {comment}")
        lines.append(f"#define {name}(X) \\")
        for row in rows:
            args = ", ".join(str(value) for value in row)
            lines.append(f"    X({args}) \\")
        lines[-1] = lines[-1].removesuffix(" \\")
        lines.append("")

    macro("FEATHER_SCALED_MM_TILES", tiles.SCALED_MM_TILES, "fp16-fp8: (warps_m, warps_n, unroll_k, repeat_m, repeat_n, pipeline)")
    macro("FEATHER_INT8_TILES", tiles.INT8_TILES, "int8 ConvRot: (warps_m, warps_n, unroll_k, repeat_m, repeat_n)")
    macro("FEATHER_CONV_TILES", tiles.CONV_TILES, "conv2d 3x3: (warps_m, warps_n, repeat_m, repeat_n, rows)")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify the committed header instead of writing it")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        current = HEADER.read_text() if HEADER.exists() else ""
        if current != rendered:
            print(f"{HEADER.relative_to(ROOT)} is stale. Run python tools/gen_tiles.py")
            return 1
        print(f"{HEADER.relative_to(ROOT)} is current")
        return 0
    HEADER.write_text(rendered)
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
